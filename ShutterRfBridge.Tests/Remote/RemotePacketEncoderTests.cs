using ShutterRfBridge.Remote;
using ShutterRfBridge.Tests.TestSupport;

namespace ShutterRfBridge.Tests.Remote;

public sealed class RemotePacketEncoderTests
{
    [Fact]
    public void Encode_MadeUpRemoteUpOnChannel3_ReturnsSyncBitsGapAndPadding()
    {
        // Sync: 41 units high (5 x 0xFF, then 0x80), 12 low. Then 40 bits of 9 units each, the last bit's low
        // replaced by the 60-unit gap: 470 units, padded with zeros to 59 bytes.
        byte[] expected =
        [
            0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x80, 0x07, 0xE3, 0x81, 0xF8, 0xE0, 0x70, 0x3F, 0x1C, 0x0F, 0xC7,
            0xE3, 0xF1, 0xC0, 0xE0, 0x70, 0x38, 0x1F, 0x8F, 0xC7, 0xE3, 0xF1, 0xF8, 0xE0, 0x70, 0x3F, 0x1F,
            0x8F, 0xC7, 0x03, 0x81, 0xC0, 0xFC, 0x70, 0x38, 0x1F, 0x8F, 0xC7, 0x03, 0x81, 0xC0, 0xFC, 0x70,
            0x38, 0x1C, 0x0F, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
        ];

        var packet = RemotePacketEncoder.Encode(new RemoteFrame(MadeUpRemote.Id, 3, RemoteCommand.Up));

        Assert.Equal(expected, packet.ToArray());
    }
}
